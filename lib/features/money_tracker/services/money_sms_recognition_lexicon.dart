  /// Number of meaningful debit phrase shapes supported by the grammar before
  /// spacing, punctuation, currency, channel, and casing variants are counted.
  static int get contextualDebitPhraseCapacity =>
      debitActions.length *
      transactionSubjects.length *
      actionConnectors.length;

  static RegExp phrasePattern(Iterable<String> phrases) {
    final alternatives =
        phrases
            .where((phrase) => phrase.trim().isNotEmpty)
            .map(_phraseToPattern)
            .toSet()
            .toList()
          ..sort((a, b) => b.length.compareTo(a.length));
    return RegExp(
      '(?<![A-Za-z0-9])(?:${alternatives.join('|')})(?![A-Za-z0-9])',
      caseSensitive: false,
    );
  }

  static String _phraseToPattern(String phrase) =>
      RegExp.escape(phrase.trim()).replaceAll(' ', r'\s+');
